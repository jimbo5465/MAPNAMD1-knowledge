"""
ابزارهای نرمال‌سازی شماره موبایل — برای تطبیق حساب‌های بله و تلگرام یک کاربر.

قالب‌های مختلفی که باید همه یکی در نظر گرفته شوند:
    +989155107315  /  989155107315  /  09155107315  /  9155107315
قاعده: تبدیل ارقام فارسی/عربی به لاتین، حذف کاراکترهای غیرعددی و پیشوندها؛
کلید مشترک مقایسه، ۱۰ رقم انتهایی (شماره محلی بدون صفر) است.
"""

from __future__ import annotations

import re

# ارقام فارسی و عربی → لاتین
_DIGIT_MAP = str.maketrans("۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩", "01234567890123456789")


def only_digits(raw: object) -> str:
    """تمام ارقام رشته را برمی‌گرداند (فارسی/عربی → لاتین، حذف بقیهٔ کاراکترها)."""
    return str(raw or "").translate(_DIGIT_MAP)


def normalize_phone(phone: object) -> str | None:
    """
    شماره را به کلید مشترک ۱۰ رقمی نرمال می‌کند؛ اگر معتبر نباشد None برمی‌گرداند.

    مثال‌ها:
        '+989155107315' → '9155107315'
        '989155107315'  → '9155107315'
        '09155107315'   → '9155107315'
        '+98 915 510 7315' → '9155107315'
        '۹۸۹۱۵۵۱۰۷۳۱۵'  → '9155107315'
    """
    digits = re.sub(r"\D", "", only_digits(phone))
    if not digits:
        return None
    if digits.startswith("00"):  # پیشوند بین‌المللی ۰۰
        digits = digits[2:]
    if len(digits) >= 12 and digits.startswith("98"):  # کد کشور ایران
        digits = digits[2:]
    digits = digits.lstrip("0")  # صفر ابتدای شماره محلی
    if len(digits) == 10:
        return digits
    return None
