ACCENT = RGBColor(0x1F, 0x4E, 0x79)


def set_rtl(paragraph):
    pPr = paragraph._p.get_or_add_pPr()
    if pPr.find(qn("w:bidi")) is None:
        pPr.append(OxmlElement("w:bidi"))


def style_run(run, size=11, bold=False, color=None, font="Tahoma"):
    run.font.name = font
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = color
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.append(rFonts)
    rFonts.set(qn("w:ascii"), font)
    rFonts.set(qn("w:hAnsi"), font)
    rFonts.set(qn("w:cs"), font)
    rtl = OxmlElement("w:rtl")
    rPr.append(rtl)


def para(doc, text="", size=11, bold=False, color=None, align=WD_ALIGN_PARAGRAPH.RIGHT,
         space_after=6, space_before=0):
    p = doc.add_paragraph()
    p.alignment = align
    set_rtl(p)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.space_before = Pt(space_before)
    if text:
        run = p.add_run(text)
        style_run(run, size=size, bold=bold, color=color)
    return p


def heading(doc, text, level=1):
    sizes = {0: 26, 1: 17, 2: 14, 3: 12.5}
    colors = {0: ACCENT, 1: ACCENT, 2: RGBColor(0x2E, 0x74, 0xB5), 3: RGBColor(0x44, 0x44, 0x44)}
    p = para(doc, text, size=sizes[level], bold=True, color=colors[level],
             align=WD_ALIGN_PARAGRAPH.RIGHT if level else WD_ALIGN_PARAGRAPH.CENTER,
             space_before=16 if level else 6, space_after=8)
    return p


def bullet(doc, text, size=11, bold=False):
    p = doc.add_paragraph(style="List Bullet")
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    set_rtl(p)
    run = p.add_run(text)
    style_run(run, size=size, bold=bold)
    return p


def numbered(doc, text, size=11):
    p = doc.add_paragraph(style="List Number")
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    set_rtl(p)
    run = p.add_run(text)
    style_run(run, size=size)
    return p


def make_table(doc, headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Light Grid Accent 1"
    # جدول راست‌به‌چپ
    tblPr = t._tbl.tblPr
    bidi = OxmlElement("w:bidiVisual")
    tblPr.append(bidi)

    hdr = t.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].text = ""
        p = hdr[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        set_rtl(p)
        run = p.add_run(h)
        style_run(run, size=10.5, bold=True)

    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
            set_rtl(p)
            run = p.add_run(str(val))
            style_run(run, size=10)
    return t


