def _legacy_to_fa(path: list[str]) -> list[str]:
    return [_EN_TO_FA_LEGACY.get(p, p) for p in path]


# ══════════════════════════════════════════════════════════════════════════════
# توابع navigation — با پشتیبانی از مسیرهای انگلیسی قدیمی
# ══════════════════════════════════════════════════════════════════════════════


def _get_subtree(tree: dict, path: list[str]) -> dict:
    node = tree
    for name in path:
        if not isinstance(node, dict) or name not in node:
            return {}
        node = node[name]
    return node if isinstance(node, dict) else {}


def get_children(path: list[str]) -> list[str]:
    # پشتیبانی از مسیر انگلیسی قدیمی
    sub = _get_subtree(KNOWLEDGE_TREE, path)
    if sub == {} and path and path[0] in _EN_TO_FA_LEGACY:
        sub = _get_subtree(KNOWLEDGE_TREE, _legacy_to_fa(path))
    return list(sub.keys())


def is_leaf(path: list[str]) -> bool:
    sub = _get_subtree(KNOWLEDGE_TREE, path)
    if sub == {} and path and path[0] in _EN_TO_FA_LEGACY:
        sub = _get_subtree(KNOWLEDGE_TREE, _legacy_to_fa(path))
        if sub != {}:
            return False
    return sub == {}


def get_leaf_paths() -> list[list[str]]:
    paths: list[list[str]] = []
    def _walk(node: dict, prefix: list[str]):
        for name, sub in node.items():
            current = prefix + [name]
            if sub == {}:
                paths.append(current)
            else:
                _walk(sub, current)
    _walk(KNOWLEDGE_TREE, [])
    return paths


def find_path_by_leaf_name(leaf_name: str) -> list[str] | None:
    for path in get_leaf_paths():
        if path[-1] == leaf_name:
            return path
    # تلاش با نگاشت فارسی
    fa = _EN_TO_FA_LEGACY.get(leaf_name)
    if fa:
        for path in get_leaf_paths():
            if path[-1] == fa:
                return path
    return None


def render_path(path: list[str]) -> str:
    return " > ".join(path)


def all_paths_as_lines() -> list[str]:
    return [render_path(p) for p in get_leaf_paths()]


def tree_as_yaml() -> str:
    lines: list[str] = []
    def _walk(node: dict, depth: int):
        for name, sub in node.items():
            lines.append("  " * depth + "- " + name)
            if sub:
                _walk(sub, depth + 1)
    _walk(KNOWLEDGE_TREE, 0)
    return "\n".join(lines)


def validate_path(path: list[str]) -> bool:
    # تلاش مستقیم فارسی
    node = KNOWLEDGE_TREE
    ok = True
    for name in path:
        if not isinstance(node, dict) or name not in node:
            ok = False
            break
        node = node[name]
    if ok:
        return True
    # تلاش با نگاشت انگلیسی قدیمی (فقط سطح ریشه فعلاً)
    fa_path = _legacy_to_fa(path)
    if fa_path == path:
        return False
    node = KNOWLEDGE_TREE
    for name in fa_path:
        if not isinstance(node, dict) or name not in node:
            return False
        node = node[name]
    return True


def total_leaf_count() -> int:
    return len(get_leaf_paths())


def total_node_count() -> int:
    count = 0
    def _walk(node: dict):
        nonlocal count
        for name, sub in node.items():
            count += 1
            if sub:
                _walk(sub)
    _walk(KNOWLEDGE_TREE)
    return count
